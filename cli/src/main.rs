use anyhow::{bail, Context, Result};
use chrono::Utc;
use clap::{Parser, Subcommand};
use std::fs;
use std::path::{Path, PathBuf};
use uuid::Uuid;

const SPEC_VERSION: &str = "PTC-0.1";

#[derive(Parser)]
#[command(name = "ptc", version, about = "Personal Time Capsule reference CLI")]
struct Cli {
    #[command(subcommand)]
    command: Command,
}

#[derive(Subcommand)]
enum Command {
    /// Scaffold a new, empty capsule at the given path.
    Init(InitArgs),
}

#[derive(clap::Args)]
struct InitArgs {
    /// Directory to create the capsule in. Must not already exist (or must be empty).
    path: PathBuf,

    /// Creator's name, written into capsule.yaml's capsule.creator.name.
    /// Optional per PRINCIPLES.md #2 -- the creator controls what
    /// identifying information appears here at all.
    #[arg(long = "creator-name")]
    creator_name: Option<String>,

    /// Creator's contact info (email, etc.), written into capsule.creator.contact.
    #[arg(long = "creator-contact")]
    creator_contact: Option<String>,

    /// Free-text description of this capsule's purpose.
    #[arg(long)]
    purpose: Option<String>,
}

fn main() -> Result<()> {
    let cli = Cli::parse();
    match cli.command {
        Command::Init(args) => init(&args),
    }
}

fn init(args: &InitArgs) -> Result<()> {
    let path = &args.path;

    if path.exists() {
        if path
            .read_dir()
            .with_context(|| format!("reading {}", path.display()))?
            .next()
            .is_some()
        {
            bail!("{} already exists and is not empty", path.display());
        }
    } else {
        fs::create_dir_all(path).with_context(|| format!("creating {}", path.display()))?;
    }

    let data_person = path.join("data").join("person");
    fs::create_dir_all(&data_person)
        .with_context(|| format!("creating {}", data_person.display()))?;

    write_bagit_txt(path)?;
    write_capsule_yaml(path, args)?;

    println!("Initialized a new capsule at {}", path.display());
    println!();
    println!("This is a capsule SKELETON, not yet a complete BagIt bag --");
    println!("no manifest-sha256.txt / tagmanifest-sha256.txt / bag-info.txt");
    println!("are written yet. Those belong to the Sealing stage");
    println!("(LIFECYCLE.md stage 5), which isn't built as a command yet.");
    println!();
    println!("Next: add content under data/, then edit capsule.yaml --");
    println!("in particular, access.default_release_policy is a placeholder");
    println!("('custom' / TBD) since `ptc init` can't choose a real release");
    println!("policy on your behalf.");

    Ok(())
}

fn write_bagit_txt(root: &Path) -> Result<()> {
    let contents = "BagIt-Version: 1.0\nTag-File-Character-Encoding: UTF-8\n";
    fs::write(root.join("bagit.txt"), contents).context("writing bagit.txt")
}

fn write_capsule_yaml(root: &Path, args: &InitArgs) -> Result<()> {
    let id = format!("urn:uuid:{}", Uuid::new_v4());
    let created = Utc::now().format("%Y-%m-%d").to_string();

    let mut yaml = String::new();
    yaml.push_str("# yaml-language-server: $schema=../schema/capsule.schema.json\n");
    yaml.push_str("# Generated by `ptc init`. See FORMAT.md for the full field reference.\n\n");
    yaml.push_str("capsule:\n");
    yaml.push_str(&format!("  spec_version: \"{}\"\n", SPEC_VERSION));
    yaml.push_str(&format!("  id: \"{}\"\n", id));
    yaml.push_str(&format!("  created: \"{}\"\n", created));

    if args.creator_name.is_some() || args.creator_contact.is_some() {
        yaml.push_str("  creator:\n");
        if let Some(name) = &args.creator_name {
            yaml.push_str(&format!("    name: {}\n", yaml_quote(name)));
        }
        if let Some(contact) = &args.creator_contact {
            yaml.push_str(&format!("    contact: {}\n", yaml_quote(contact)));
        }
    }

    if let Some(purpose) = &args.purpose {
        yaml.push_str("\npurpose:\n");
        yaml.push_str(&format!("  description: {}\n", yaml_quote(purpose)));
    }

    yaml.push_str("\naccess:\n");
    yaml.push_str("  # Defaulted to the more conservative zone; edit once you've decided.\n");
    yaml.push_str("  default_privacy_zone: restricted\n");
    yaml.push_str("  default_release_policy:\n");
    yaml.push_str("    # ptc init cannot choose a release policy on your behalf --\n");
    yaml.push_str("    # replace this with a real policy (see FORMAT.md, `access` section).\n");
    yaml.push_str("    type: custom\n");
    yaml.push_str("    description: \"TBD -- set by the creator\"\n");

    yaml.push_str("\nintegrity:\n");
    yaml.push_str("  manifest_algorithm: sha256\n");

    yaml.push_str("\nstatus:\n");
    yaml.push_str("  lifecycle_stage: origination\n");

    fs::write(root.join("capsule.yaml"), yaml).context("writing capsule.yaml")
}

/// Minimal YAML double-quoted scalar escaping, sufficient for the plain
/// user-supplied strings this CLI accepts (names, contact info, short
/// descriptions). Not a general-purpose YAML emitter.
fn yaml_quote(s: &str) -> String {
    format!("\"{}\"", s.replace('\\', "\\\\").replace('"', "\\\""))
}
